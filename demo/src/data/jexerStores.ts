import type { Equipment, Gym } from '../types/gym'

function inferEquipment(name: string): Equipment[] {
  if (name.includes('ライトジム')) {
    return ['ダンベル', 'マシン', 'ヨガマット', '自重']
  }
  if (name.includes('フィットネススタジオ')) {
    return ['マシン', 'ヨガマット', 'ダンベル', '自重']
  }
  if (name.includes('リフレッシュスタジオ')) {
    return ['マシン', 'ヨガマット', '自重']
  }
  if (name.includes('フィットネスガーデン')) {
    return ['マシン', 'ヨガマット', '自重']
  }
  if (name.includes('ジム フラット')) {
    return ['マシン', 'ダンベル', '自重']
  }
  if (name.includes('キッズ')) {
    return ['マシン', 'ヨガマット', '自重']
  }
  if (name.includes('テニススクール')) {
    return ['ヨガマット', '自重']
  }
  if (name.includes('THE JEXER') || name.includes('Fitness Lounge')) {
    return ['ラック', 'バーベル', 'ダンベル', 'ケーブル', 'マシン', 'ヨガマット']
  }
  return ['ラック', 'バーベル', 'ダンベル', 'ケーブル', 'マシン', 'ヨガマット']
}

